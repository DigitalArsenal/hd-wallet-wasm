import fs from 'node:fs';
import path from 'node:path';
import { Buffer } from 'node:buffer';
import { fileURLToPath } from 'node:url';

import { encodeSdnPluginManifest } from '../wasm/src/sdn-plugin-manifest-codec.mjs';
import {
  HD_WALLET_SDN_PLUGIN_MANIFEST,
} from '../wasm/src/sdn-plugin-manifest-source.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');

function renderByteRows(bytes) {
  const rows = [];
  for (let index = 0; index < bytes.length; index += 12) {
    const slice = bytes.subarray(index, index + 12);
    rows.push(
      `  ${Array.from(slice, (value) => `0x${value.toString(16).padStart(2, '0')}`).join(', ')}`
    );
  }
  return rows.join(',\n');
}

function writeFileIfChanged(filePath, contents) {
  const current = fs.existsSync(filePath)
    ? fs.readFileSync(filePath, 'utf8')
    : null;
  if (current === contents) {
    return false;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, contents);
  return true;
}

function writeBinaryIfChanged(filePath, bytes) {
  const current = fs.existsSync(filePath) ? fs.readFileSync(filePath) : null;
  if (current && Buffer.compare(current, Buffer.from(bytes)) === 0) {
    return false;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, bytes);
  return true;
}

const manifestBytes = encodeSdnPluginManifest(HD_WALLET_SDN_PLUGIN_MANIFEST);
const manifestBase64 = Buffer.from(manifestBytes).toString('base64');

const binaryPath = path.join(
  repoRoot,
  'generated',
  'sdn',
  'hd_wallet_sdn_plugin_manifest.fb'
);
const cppSourcePath = path.join(
  repoRoot,
  'generated',
  'sdn',
  'plugin_manifest_exports.cpp'
);
const jsModulePath = path.join(
  repoRoot,
  'wasm',
  'src',
  'generated',
  'sdn_plugin_manifest.mjs'
);

writeBinaryIfChanged(binaryPath, manifestBytes);
writeFileIfChanged(
  cppSourcePath,
  `#include <stdint.h>

namespace {
static const uint8_t g_hd_wallet_sdn_plugin_manifest[] = {
${renderByteRows(manifestBytes)}
};
}  // namespace

extern "C" const uint8_t* plugin_get_manifest_flatbuffer(void) {
  return g_hd_wallet_sdn_plugin_manifest;
}

extern "C" uint32_t plugin_get_manifest_flatbuffer_size(void) {
  return static_cast<uint32_t>(sizeof(g_hd_wallet_sdn_plugin_manifest));
}
`
);
writeFileIfChanged(
  jsModulePath,
  `/**
 * Auto-generated embedded SDN plugin manifest bytes.
 * DO NOT EDIT - Generated by scripts/generate-sdn-plugin-manifest.mjs
 */

export const manifestBase64 = '${manifestBase64}';
export const manifestByteLength = ${manifestBytes.length};
`
);

console.log(
  `Generated SDN plugin manifest artifacts (${manifestBytes.length} bytes)`
);
console.log(`  Binary: ${path.relative(repoRoot, binaryPath)}`);
console.log(`  C++:    ${path.relative(repoRoot, cppSourcePath)}`);
console.log(`  JS:     ${path.relative(repoRoot, jsModulePath)}`);

