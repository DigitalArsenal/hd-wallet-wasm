#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const EXPECTED_BYTES = 73017;
const EXPECTED_SHA256 =
  '4adb3f0afb4a10cf19ebe48d8c69a46f934bbc8d77c694c210564f9583e7f4ba';
const EXPECTED_ENTRIES = 10000;

const sourceUrl = new URL('../wallet-ui/data/common-passwords-sdn-v1.txt', import.meta.url);
const outputUrl = new URL('../generated/common_passwords_sdn_v1.inc', import.meta.url);

function fail(message) {
  throw new Error(`password corpus embed failed: ${message}`);
}

const args = process.argv.slice(2);
const checkOnly = args.length === 1 && args[0] === '--check';
if (args.length !== 0 && !checkOnly) {
  fail('usage: node scripts/embed-password-corpus.mjs [--check]');
}

const source = readFileSync(sourceUrl);
if (source.length !== EXPECTED_BYTES) {
  fail(`expected ${EXPECTED_BYTES} bytes, found ${source.length}`);
}
const digest = createHash('sha256').update(source).digest('hex');
if (digest !== EXPECTED_SHA256) {
  fail(`SHA-256 mismatch: ${digest}`);
}
if (source.includes(0x0d)) fail('CR bytes are forbidden');

const text = new TextDecoder('utf-8', { fatal: true }).decode(source);
if (!text.endsWith('\n')) fail('source must end with exactly one LF');
const entries = text.slice(0, -1).split('\n');
if (entries.length !== EXPECTED_ENTRIES) {
  fail(`expected ${EXPECTED_ENTRIES} entries, found ${entries.length}`);
}
if (entries.some((entry) => entry.length === 0)) fail('empty entry');
if (new Set(entries).size !== entries.length) fail('duplicate entry');
for (const entry of entries) {
  if (!/^[\x21-\x7e]+$/u.test(entry)) fail(`non-printable entry: ${JSON.stringify(entry)}`);
  if (entry !== entry.toLowerCase()) fail(`non-lowercase entry: ${JSON.stringify(entry)}`);
}

const sorted = [...entries].sort();
const generated = [
  '// Generated by scripts/embed-password-corpus.mjs; do not edit.',
  `// Source bytes: ${EXPECTED_BYTES}; SHA-256: ${EXPECTED_SHA256}`,
  `inline constexpr std::array<std::string_view, ${EXPECTED_ENTRIES}> kCommonPasswordsSdnV1 = {{`,
  ...sorted.map((entry) => `    ${JSON.stringify(entry)},`),
  '}};',
  '',
].join('\n');

if (checkOnly) {
  let current;
  try {
    current = readFileSync(outputUrl, 'utf8');
  } catch (error) {
    fail(`cannot read ${fileURLToPath(outputUrl)}: ${error.message}`);
  }
  if (current !== generated) fail(`${fileURLToPath(outputUrl)} is stale`);
} else {
  writeFileSync(outputUrl, generated, { encoding: 'utf8', mode: 0o644 });
}

console.log(`password corpus embed: PASS (${checkOnly ? 'checked' : 'wrote'} ${EXPECTED_ENTRIES} entries)`);
